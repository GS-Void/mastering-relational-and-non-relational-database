-- Tabela de Usuários
CREATE TABLE TB_VOID_USUARIO (
    ID NUMBER PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    CPF VARCHAR2(11) UNIQUE NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    TIPO_USUARIO CHAR(1) NOT NULL
);

-- Sequência para geração automática do ID de usuários 
CREATE SEQUENCE SEQ_TB_USUARIO START WITH 11 INCREMENT BY 1;

-- Dados medicos do paciente
CREATE TABLE TB_VOID_PACIENTE (
    ID_USUARIO NUMBER PRIMARY KEY,
    LIMITE_ESFORCO_CRITICO NUMBER(5,2) NOT NULL,
    CONSTRAINT FK_PAC_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_VOID_USUARIO(ID)
);

-- Identificaçao do fisioterapeuta
CREATE TABLE TB_VOID_FISIOTERAPEUTA (
    ID_USUARIO NUMBER PRIMARY KEY,
    REGISTRO_PROFISSIONAL VARCHAR2(20) UNIQUE NOT NULL,
    CONSTRAINT FK_FIS_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_VOID_USUARIO(ID)
);

-- Tabela para carga espaciais
CREATE TABLE PROTOCOLO_ESPACIAL (
    ID_PROTOCOLO NUMBER PRIMARY KEY,
    NOME_PROTOCOLO VARCHAR2(100) NOT NULL,
    LIMITE_FADIGA_MAXIMA NUMBER(5,2) NOT NULL
);

-- Controle dos dispositivos esp32 cadastrados
CREATE TABLE SENSOR_WEARABLE (
    ID_SENSOR NUMBER PRIMARY KEY,
    MAC_ADDRESS VARCHAR2(17) UNIQUE NOT NULL,
    STATUS VARCHAR2(10) DEFAULT 'ATIVO'
);

-- Controle de agendamento e execucao dos treinos
CREATE TABLE TB_VOID_SESSAO_REABILITACAO (
    PACIENTE_ID NUMBER NOT NULL,
    DATA_SESSAO DATE NOT NULL,
    DESGASTE_ACUMULADO NUMBER(5,2),
    ALERTA_FADIGA_CRITICA NUMBER(1) DEFAULT 0,
    ID_FISIO NUMBER NOT NULL,
    ID_PROTOCOLO NUMBER NOT NULL,
    STATUS_SESSAO VARCHAR2(20) DEFAULT 'ANDAMENTO',
    CONSTRAINT PK_SESSAO PRIMARY KEY (PACIENTE_ID, DATA_SESSAO),
    CONSTRAINT FK_SESSAO_PAC FOREIGN KEY (PACIENTE_ID) REFERENCES TB_VOID_PACIENTE(ID_USUARIO),
    CONSTRAINT FK_SESSAO_FIS FOREIGN KEY (ID_FISIO) REFERENCES TB_VOID_FISIOTERAPEUTA(ID_USUARIO),
    CONSTRAINT FK_SESSAO_PROT FOREIGN KEY (ID_PROTOCOLO) REFERENCES PROTOCOLO_ESPACIAL(ID_PROTOCOLO)
);

-- Tabela de telemetria 
CREATE TABLE LEITURA_FADIGA (
    PACIENTE_ID NUMBER NOT NULL,
    DATA_SESSAO DATE NOT NULL,
    SEGUNDO_LEITURA NUMBER NOT NULL,
    ID_SENSOR NUMBER NOT NULL,
    PERCENTUAL_DESGASTE NUMBER(5,2) NOT NULL,
    CONSTRAINT PK_LEITURA PRIMARY KEY (PACIENTE_ID, DATA_SESSAO, SEGUNDO_LEITURA),
    CONSTRAINT FK_LEIT_SESSAO FOREIGN KEY (PACIENTE_ID, DATA_SESSAO) REFERENCES TB_VOID_SESSAO_REABILITACAO(PACIENTE_ID, DATA_SESSAO) ON DELETE CASCADE,
    CONSTRAINT FK_LEIT_SENSOR FOREIGN KEY (ID_SENSOR) REFERENCES SENSOR_WEARABLE(ID_SENSOR)
);

-- Historico de quebras de limite de segurança
CREATE TABLE ALERTA_CRITICO (
    ID_ALERTA NUMBER PRIMARY KEY,
    PACIENTE_ID NUMBER NOT NULL,
    DATA_SESSAO DATE NOT NULL,
    TIMESTAMP_ALERTA TIMESTAMP NOT NULL,
    NIVEL_ATINGIDO NUMBER(5,2),
    CONSTRAINT FK_ALERTA_SESSAO FOREIGN KEY (PACIENTE_ID, DATA_SESSAO) REFERENCES TB_VOID_SESSAO_REABILITACAO(PACIENTE_ID, DATA_SESSAO) ON DELETE CASCADE
);

CREATE SEQUENCE SEQ_ALERTA START WITH 1 INCREMENT BY 1;

-- Auditoria de atualizacoes na sessao
CREATE TABLE LOG_AUDITORIA_SESSAO (
    DATA_HORA TIMESTAMP,
