-- Loop FOR e INSERT com variável
DECLARE
    v_desgaste NUMBER;
    e_desgaste_invalido EXCEPTION;
BEGIN
    FOR i IN 1..85 LOOP
        v_desgaste := 10 + (i * 0.8); 
        
        -- desgaste não pode passar de 100%
        IF v_desgaste > 100 THEN 
            RAISE e_desgaste_invalido; 
        END IF;
        
        INSERT INTO LEITURA_FADIGA (PACIENTE_ID, DATA_SESSAO, SEGUNDO_LEITURA, ID_SENSOR, PERCENTUAL_DESGASTE)
        VALUES (1, TO_DATE('2026-05-01', 'YYYY-MM-DD'), i + 3, 1, v_desgaste);
    END LOOP;
    COMMIT;
EXCEPTION
    WHEN e_desgaste_invalido THEN 
        DBMS_OUTPUT.PUT_LINE('Erro de Regra de Negócio: Percentual de desgaste excedeu 100%.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Erro inesperado durante a inserção: ' || SQLERRM);
END;
/

-- Cursor Explícito, LOOP e Condicional
DECLARE
    CURSOR c_leituras IS 
        SELECT SEGUNDO_LEITURA, PERCENTUAL_DESGASTE 
        FROM LEITURA_FADIGA 
        WHERE PACIENTE_ID = 2;
        
    v_segundo LEITURA_FADIGA.SEGUNDO_LEITURA%TYPE;
    v_perc LEITURA_FADIGA.PERCENTUAL_DESGASTE%TYPE;
BEGIN
    OPEN c_leituras;
    LOOP
        FETCH c_leituras INTO v_segundo, v_perc;
        EXIT WHEN c_leituras%NOTFOUND;
        
        IF v_perc > 80.00 THEN
            DBMS_OUTPUT.PUT_LINE('CRÍTICO: Desgaste altíssimo no segundo ' || v_segundo || ' (' || v_perc || '%)');
        ELSIF v_perc > 70.00 THEN
            DBMS_OUTPUT.PUT_LINE('Alerta: Desgaste alto no segundo ' || v_segundo || ' (' || v_perc || '%)');
        ELSE
            DBMS_OUTPUT.PUT_LINE('Desgaste normal no segundo ' || v_segundo);
        END IF;
    END LOOP;
    CLOSE c_leituras;
EXCEPTION
    WHEN OTHERS THEN 
        DBMS_OUTPUT.PUT_LINE('Erro ao processar leituras de fadiga: ' || SQLERRM);
END;
/

-- Cursor Explícito WHILE LOOP
DECLARE
    CURSOR c_sensores IS 
        SELECT ID_SENSOR, STATUS 
        FROM SENSOR_WEARABLE;
        
    v_id SENSOR_WEARABLE.ID_SENSOR%TYPE;
    v_status SENSOR_WEARABLE.STATUS%TYPE;
BEGIN
    OPEN c_sensores;
    FETCH c_sensores INTO v_id, v_status;
    
    WHILE c_sensores%FOUND LOOP
        IF v_status = 'ATIVO' THEN
            DBMS_OUTPUT.PUT_LINE('Sensor ' || v_id || ' operante e enviando telemetria.');
        ELSE
            DBMS_OUTPUT.PUT_LINE('Sensor ' || v_id || ' inativo ou aguardando manutenção.');
        END IF;
        FETCH c_sensores INTO v_id, v_status;
    END LOOP;
    
    CLOSE c_sensores;
EXCEPTION
    WHEN OTHERS THEN 
        DBMS_OUTPUT.PUT_LINE('Erro na varredura de sensores: ' || SQLERRM);
END;
/
 
-- Cursor Explícito (DELETE)
DECLARE
    CURSOR c_sessoes_canceladas IS 
        SELECT PACIENTE_ID, DATA_SESSAO 
        FROM TB_VOID_SESSAO_REABILITACAO 
        WHERE STATUS_SESSAO = 'CANCELADA';
        
    v_paciente TB_VOID_SESSAO_REABILITACAO.PACIENTE_ID%TYPE;
    v_data TB_VOID_SESSAO_REABILITACAO.DATA_SESSAO%TYPE;
    e_sem_dados EXCEPTION;
BEGIN
    OPEN c_sessoes_canceladas;
    LOOP
        FETCH c_sessoes_canceladas INTO v_paciente, v_data;
        EXIT WHEN c_sessoes_canceladas%NOTFOUND;
        
        DELETE FROM TB_VOID_SESSAO_REABILITACAO 
        WHERE PACIENTE_ID = v_paciente AND DATA_SESSAO = v_data;
    END LOOP;
    
    IF c_sessoes_canceladas%ROWCOUNT = 0 THEN
        RAISE e_sem_dados;
    END IF;
    
    CLOSE c_sessoes_canceladas;
    COMMIT;
EXCEPTION
    WHEN e_sem_dados THEN 
        DBMS_OUTPUT.PUT_LINE('Limpeza: Nenhuma sessão cancelada encontrada para exclusão.');
    WHEN OTHERS THEN 
        DBMS_OUTPUT.PUT_LINE('Erro ao excluir sessões: ' || SQLERRM);
END;
/

-- Cursor Explícito FOR UPDATE e Condicional
DECLARE
    CURSOR c_equip IS 
        SELECT ID_SENSOR 
        FROM SENSOR_WEARABLE 
        FOR UPDATE;
        
    v_id_sensor SENSOR_WEARABLE.ID_SENSOR%TYPE;
BEGIN
    OPEN c_equip;
    LOOP
        FETCH c_equip INTO v_id_sensor;
        EXIT WHEN c_equip%NOTFOUND;
        
        IF v_id_sensor = 1 THEN
            UPDATE SENSOR_WEARABLE 
            SET STATUS = 'CALIBRACAO' 
            WHERE CURRENT OF c_equip;
        END IF;
    END LOOP;
    CLOSE c_equip;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN 
        DBMS_OUTPUT.PUT_LINE('Erro na atualização de calibração de sensores: ' || SQLERRM);
END;
/

