        DBMS_OUTPUT.PUT_LINE('Usuário validado como Paciente apto para protocolo espacial.');
    ELSIF v_tipo_usuario = 'F' THEN
        DBMS_OUTPUT.PUT_LINE('Usuário validado como Fisioterapeuta responsável.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Tipo de usuário desconhecido no sistema.');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Erro: Usuário não encontrado no banco de dados.');
    WHEN TOO_MANY_ROWS THEN
        DBMS_OUTPUT.PUT_LINE('Erro de Integridade: Mais de um usuário retornado para o mesmo ID.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Erro inesperado na validação de usuário: ' || SQLERRM);
END;
/

