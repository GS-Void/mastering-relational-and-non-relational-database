-- Relatório de sessões de reabilitação
SELECT 
    s.DATA_SESSAO, 
    p.NOME AS PACIENTE, 
    f.NOME AS FISIOTERAPEUTA, 
    pr.NOME_PROTOCOLO, 
    s.STATUS_SESSAO
FROM TB_VOID_SESSAO_REABILITACAO s
INNER JOIN TB_VOID_USUARIO p ON s.PACIENTE_ID = p.ID
INNER JOIN TB_VOID_USUARIO f ON s.ID_FISIO = f.ID
INNER JOIN PROTOCOLO_ESPACIAL pr ON s.ID_PROTOCOLO = pr.ID_PROTOCOLO
ORDER BY s.DATA_SESSAO DESC;

-- Relatório de alertas críticos vs limite de segurança do paciente
SELECT 
    a.TIMESTAMP_ALERTA, 
    u.NOME AS PACIENTE, 
    a.NIVEL_ATINGIDO AS DESGASTE_REGISTRADO, 
    p.LIMITE_ESFORCO_CRITICO AS LIMITE_PERMITIDO
FROM ALERTA_CRITICO a
INNER JOIN TB_VOID_PACIENTE p ON a.PACIENTE_ID = p.ID_USUARIO
INNER JOIN TB_VOID_USUARIO u ON p.ID_USUARIO = u.ID
ORDER BY a.TIMESTAMP_ALERTA DESC;

-- Relatório de desgaste excessivo por equipamento wearable
SELECT 
    l.DATA_SESSAO, 
    l.SEGUNDO_LEITURA, 
    l.PERCENTUAL_DESGASTE, 
    sw.MAC_ADDRESS, 
    sw.STATUS AS STATUS_WEARABLE
FROM LEITURA_FADIGA l
INNER JOIN SENSOR_WEARABLE sw ON l.ID_SENSOR = sw.ID_SENSOR
WHERE l.PERCENTUAL_DESGASTE > 80
ORDER BY l.PERCENTUAL_DESGASTE DESC;

-- Relatório de vínculo: Pacientes e os Fisioterapeutas que os atenderam
SELECT DISTINCT 
    u_pac.NOME AS NOME_PACIENTE, 
    u_fis.NOME AS NOME_FISIOTERAPEUTA, 
    fis.REGISTRO_PROFISSIONAL AS CREFITO
FROM TB_VOID_SESSAO_REABILITACAO s
INNER JOIN TB_VOID_USUARIO u_pac ON s.PACIENTE_ID = u_pac.ID
INNER JOIN TB_VOID_FISIOTERAPEUTA fis ON s.ID_FISIO = fis.ID_USUARIO
INNER JOIN TB_VOID_USUARIO u_fis ON fis.ID_USUARIO = u_fis.ID;

