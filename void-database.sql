-- Criação do Package Body
CREATE OR REPLACE PACKAGE BODY PKG_VOID_SYSTEM AS

    -- Para cancelar sessões de forma segura
    PROCEDURE PR_CANCELA_SESSAO(p_paciente_id NUMBER, p_data DATE) IS
    BEGIN
        UPDATE TB_VOID_SESSAO_REABILITACAO 
        SET STATUS_SESSAO = 'CANCELADA' 
        WHERE PACIENTE_ID = p_paciente_id AND DATA_SESSAO = p_data;
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN 
            DBMS_OUTPUT.PUT_LINE('Erro ao executar procedure de cancelamento: ' || SQLERRM);
            ROLLBACK;
    END PR_CANCELA_SESSAO;

    -- Contabilizar o número de alertas críticos de um paciente
    FUNCTION FN_TOTAL_ALERTAS(p_paciente_id NUMBER) RETURN NUMBER IS
        v_total NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_total 
        FROM ALERTA_CRITICO 
        WHERE PACIENTE_ID = p_paciente_id;
        
        RETURN v_total;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN 
            RETURN 0;
        WHEN OTHERS THEN
            RETURN -1;
    END FN_TOTAL_ALERTAS;

END PKG_VOID_SYSTEM;
